def extract_type(text, name):
    m = re.search(rf"^\s*type {name} = ", text, re.M)
    i, depth = text.index("{", m.end()), 0
    for j in range(i, len(text)):
        depth += text[j] == "{"
        depth -= text[j] == "}"
        if depth == 0:
            return text[m.start():j + 1], text[:m.start()].count("\n") + 1
    raise ValueError(name)


