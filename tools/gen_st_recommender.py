        f"\tif = {{ limit = {{ has_variable = st_rec_c{n} }}\n"
        f"\t\tdebug_log = \"ST_REC|ROW|[TimeKeeper.GetCurrentDate.GetString]|{n}|"
        f"[THIS.Var('st_rec_k{n}').GetGoods.GetKey]|[THIS.Var('st_rec_c{n}').GetCountry.GetNameNoFormatting]|"
