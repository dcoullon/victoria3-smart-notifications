# Self-test: the effect's steps in Python, against brute force.
# ---------------------------------------------------------------------------
def rule_spread(bh, sh, bp, sp, k, t):
    b, s = bh + t, sp + t
    rh = (b - sh) / max(min(b, sh), 0.01)
    rp = (bp - s) / max(min(bp, s), 0.01)
    c = lambda r: max(-1.0, min(1.0, r))
    return k * (c(rp) - c(rh)), rh, rp, b, s


def gain(m, t):
    sp_, *_ = rule_spread(m["bh"], m["sh"], m["bp"], m["sp"], m["k"], t)
    return t * (sp_ - m["ship"])


def marginal(m, t):
    k, sh, bp = m["k"], m["sh"], m["bp"]
    spread, rh, rp, b, s = rule_spread(m["bh"], sh, bp, m["sp"], k, t)
    slope_h = max(k / max(sh, .01), k * sh / max(b, .01) / max(b, .01)) if -1 < rh < 1 else 0
    slope_p = max(k * bp / max(s, .01) / max(s, .01), k / max(bp, .01)) if -1 < rp < 1 else 0
    return spread - m["ship"] - t * (slope_h + slope_p)


def port(m):
    """st_rec_search, line for line."""
    cap = m["cap"]
    if gain(m, 10) <= 0:
        return None
    q = 10.0
    for f in FACTORS:
        t = max(q * f, q + 1)
        if cap - t >= 0 and marginal(m, t) > 0:
            q = t
    if marginal(m, cap) > 0:
        q = cap

    def better(t, q):
        return t if cap - t >= 0 and gain(m, t) - gain(m, q) > 0 else q
    for kink in (max(m["bp"] / 2 - m["sp"], 10), max(m["sh"] / 2 - m["bh"], 10)):
        if kink - q > 0 and min(q * 1.2 + 2, cap) - kink >= 0:
            q = better(kink, q)
    q = better(q + 1, q)
    return q


def selftest(n=5000, seed=7):
    rnd = random.Random(seed)
    short, worst, tested = 0, 0.0, 0
    for _ in range(n):
        lg = lambda: 10 ** rnd.uniform(0.5, 4)
        m = dict(bh=lg(), sh=lg(), bp=lg(), sp=lg(), k=0.75 * rnd.uniform(10, 120))
        m["ship"] = rnd.choice([0, rnd.uniform(0, 15)])
        m["cap"] = max(10.0, min(m["bp"] - m["sp"] + 10, rnd.uniform(50, 20000)))
        q = port(m)
        if q is None:
            continue
        tested += 1
        brute = max(gain(m, x) for x in [10 + i * (m["cap"] - 10) / 4000 for i in range(4001)])
        got = gain(m, q)
        if brute > 0:
            gap = (brute - got) / brute
            worst = max(worst, gap)
            short += gap > 0.02
    print(f"self-test: {tested} profitable shapes of {n}; {short} more than 2% below brute force "
          f"({100 * short / max(tested, 1):.2f}%); worst {100 * worst:.2f}%")
    return short / max(tested, 1) < 0.02


