def goods_table():
    """[(key, traded_quantity)] from the installed game, file order."""
    text = (GAME / "common/goods/00_goods.txt").read_text(encoding="utf-8-sig")
    out = []
    for m in re.finditer(r"^(\w+)\s*=\s*\{(.*?)^\}", text, re.M | re.S):
        tq = re.search(r"\btraded_quantity\s*=\s*([\d.]+)", m[2])
        if tq:
            out.append((m[1], float(tq[1])))
    return out


def fnum(x):
    s = f"{x:.5f}".rstrip("0").rstrip(".")
    return s if s else "0"


