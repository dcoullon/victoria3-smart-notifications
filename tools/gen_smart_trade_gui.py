def render() -> str:
    text = TEMPLATE
    # Longest names first so @@A_NET_LANE@@ is never clobbered by a shorter token.
    for name in sorted(TOKENS, key=len, reverse=True):
        text = text.replace(f"@@{name}@@", TOKENS[name])
    assert "@@" not in text, [l for l in text.splitlines() if "@@" in l][:3]
    return "﻿" + text


if __name__ == "__main__":
    want = render()
    if "--check" in sys.argv:
        have = OUT.read_text(encoding="utf-8") if OUT.is_file() else ""
        if have != want:
            print(f"STALE: {OUT.relative_to(REPO)} differs from the generator; rerun it.")
            sys.exit(1)
        print("OK: 00_smart_trade.gui matches the generator.")
        sys.exit(0)
    OUT.write_text(want, encoding="utf-8")
    print(f"wrote {OUT.relative_to(REPO)} ({len(want.splitlines())} lines)")
