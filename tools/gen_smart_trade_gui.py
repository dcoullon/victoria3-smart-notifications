"""Build smart_trade/gui/00_smart_trade.gui from a readable template.

The GUI has no variables, so every number is one nested expression, often
300+ characters (a first-week price after the transfer is ~10 levels deep).
Writing those by hand is how typos survive. Here each formula is defined
once by name (@@NAME@@ tokens) and expanded into the template.

Usage:  python tools/gen_smart_trade_gui.py           (writes the file)
        python tools/gen_smart_trade_gui.py --check   (exit 1 if stale)
"""
