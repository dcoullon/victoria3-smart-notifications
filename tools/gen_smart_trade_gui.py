D_SHIP_HI = mul(D_SHIP_LO, fx(1.5))
D_NET_LO = sub(D_MARGIN, D_SHIP_HI)
D_NET_HI = sub(D_MARGIN, D_SHIP_LO)
D_BREAKEVEN = div(mul(sub(D_PP1, D_PH1), D_TQ), MMP)
